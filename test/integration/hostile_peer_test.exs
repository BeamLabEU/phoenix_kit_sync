defmodule PhoenixKitSync.Integration.HostilePeerTest do
  use PhoenixKitSync.DataCase, async: false

  alias PhoenixKitSync.Client
  alias PhoenixKitSync.ConnectionNotifier
  alias PhoenixKitSync.Connections
  alias PhoenixKitSync.DataImporter
  alias PhoenixKitSync.Test.StubRemote
  alias PhoenixKitSync.Web.ConnectionsLive.Status
  alias PhoenixKitSync.WebSocketClient

  # What a broken or hostile sender can put on the wire, and what this site
  # does with it: one bad record costs one record, a page that repeats ends
  # the transfer, an answer that is too large is dropped.

  @table "hp_rows"

  setup do
    repo().query!("""
    CREATE TABLE #{@table} (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      label text,
      price numeric
    )
    """)

    :ok
  end

  defp repo, do: PhoenixKit.RepoHelper.repo()

  defp labels, do: repo().query!("SELECT label FROM #{@table} ORDER BY id").rows |> List.flatten()

  describe "DataImporter.import_records/3 with unreadable values" do
    @bad_values [
      %{"__type__" => "decimal", "value" => "x"},
      %{"__type__" => "decimal", "value" => 5},
      %{"__type__" => "decimal", "value" => nil},
      %{"__type__" => "datetime", "value" => 5},
      %{"__type__" => "date", "value" => ["2026-01-01"]},
      %{"__type__" => "time", "value" => %{"a" => 1}}
    ]

    for {bad, index} <- Enum.with_index(@bad_values), strategy <- [:skip, :overwrite, :append] do
      test "#{inspect(bad)} under #{strategy} (case #{index}) fails its own record only" do
        records = [
          %{"id" => 1, "label" => "first"},
          %{"id" => 2, "label" => "bad", "price" => unquote(Macro.escape(bad))},
          %{"id" => 3, "label" => "last"}
        ]

        assert {:ok, result} = DataImporter.import_records(@table, records, unquote(strategy))

        assert result.created == 2
        assert [{%{"id" => 2}, reason}] = result.errors
        assert is_binary(reason)
        assert labels() == ["first", "last"]
      end
    end

    test "a record that is not a map is that record's error" do
      records = [
        %{"id" => 1, "label" => "first"},
        5,
        "text",
        nil,
        [1],
        %{"id" => 2, "label" => "b"}
      ]

      assert {:ok, result} = DataImporter.import_records(@table, records, :skip)
      assert result.created == 2
      assert length(result.errors) == 4
      assert labels() == ["first", "b"]
    end

    test "a well-formed wrapped decimal still imports" do
      record = %{
        "id" => 1,
        "label" => "ok",
        "price" => %{"__type__" => "decimal", "value" => "1.50"}
      }

      assert {:ok, %{created: 1, errors: []}} =
               DataImporter.import_records(@table, [record], :skip)

      assert %{rows: [[price]]} = repo().query!("SELECT price FROM #{@table}")
      assert Decimal.equal?(price, Decimal.new("1.50"))
    end
  end

  describe "Client.transfer/3 against a sender that ignores the offset" do
    # Stands in for the WebSocket client process: answers every schema and
    # records request the way a sender would, with whatever `page` returns
    # for the offset asked.
    defp fake_sender(page) do
      caller = self()

      spawn_link(fn ->
        fake_sender_loop(caller, page, 0)
      end)
    end

    defp fake_sender_loop(caller, page, requests) do
      receive do
        {:"$websockex_cast", {:request_schema, table}} ->
          send(
            caller,
            {:sync_client, {:schema, table, %{"columns" => [], "primary_key" => ["id"]}}}
          )

          fake_sender_loop(caller, page, requests)

        {:"$websockex_cast", {:request_records, table, opts}} ->
          records = page.(opts[:offset], requests)
          send(caller, {:sync_client, {:records, table, %{records: records, has_more: true}}})
          fake_sender_loop(caller, page, requests + 1)

        {:requests, from} ->
          send(from, {:requests, requests})
          fake_sender_loop(caller, page, requests)
      end
    end

    defp requests(sender) do
      send(sender, {:requests, self()})
      assert_receive {:requests, count}
      count
    end

    @tag timeout: 20_000
    test "the same page twice ends the transfer instead of looping forever" do
      same_page = fn _offset, _n ->
        [%{"id" => 1, "label" => "a"}, %{"id" => 2, "label" => "b"}]
      end

      sender = fake_sender(same_page)

      assert {:error, :paging_stalled} = Client.transfer(sender, @table, strategy: :skip)

      # The first page was imported once; the repeat was not.
      assert labels() == ["a", "b"]
      assert requests(sender) == 2
    end

    @tag timeout: 20_000
    test "pages that advance are read to the empty one" do
      pages = fn
        0, _n -> [%{"id" => 1, "label" => "a"}, %{"id" => 2, "label" => "b"}]
        2, _n -> [%{"id" => 3, "label" => "c"}]
        3, _n -> []
      end

      assert {:ok, %{created: 3}} = Client.transfer(fake_sender(pages), @table, strategy: :skip)
      assert labels() == ["a", "b", "c"]
    end

    @tag timeout: 20_000
    test "an answer whose records are not a list is an invalid response" do
      sender = fake_sender(fn _offset, _n -> "not a page" end)
      assert {:error, :invalid_response} = Client.transfer(sender, @table, strategy: :skip)
    end
  end

  describe "WebSocketClient.handle_frame/2" do
    setup do
      {:ok,
       state: %WebSocketClient{
         url: "ws://example.com",
         code: "ABCD2345",
         caller: self(),
         receiver_info: %{},
         ref_counter: 0,
         pending_refs: %{"1" => {:records, @table}, "2" => :tables, "3" => {:count, @table}},
         joined: true,
         heartbeat_ref: nil
       }}
    end

    test "valid JSON that is not a channel frame is ignored", %{state: state} do
      for frame <- [
            "{}",
            "5",
            "null",
            ~s("x"),
            "[]",
            "[1,2]",
            "[1,2,3,4,5,6]",
            ~s([1,2,{"a":1},"e",{}])
          ] do
        assert {:ok, ^state} = WebSocketClient.handle_frame({:text, frame}, state), frame
      end

      refute_received {:sync_client, _}
    end

    test "a response whose body has the wrong shape does not crash the client", %{state: state} do
      frames = [
        ["transfer:ABCD2345", "response:records", %{"records" => "x", "ref" => "1"}],
        ["transfer:ABCD2345", "response:records", [1, 2]],
        ["transfer:ABCD2345", "response:records", 7],
        ["transfer:ABCD2345", "response:tables", %{"tables" => %{"a" => 1}, "ref" => "2"}],
        ["transfer:ABCD2345", "response:count", %{"count" => %{"a" => 1}, "ref" => "3"}],
        ["transfer:ABCD2345", "response:error", %{"error" => %{"a" => 1}, "ref" => "9"}]
      ]

      for [topic, event, payload] <- frames do
        frame = Jason.encode!([nil, nil, topic, event, payload])
        assert {:ok, %WebSocketClient{}} = WebSocketClient.handle_frame({:text, frame}, state)
      end

      refute_received {:sync_client, {:records, _table, _result}}
      refute_received {:sync_client, {:tables, _tables}}
      refute_received {:sync_client, {:count, _table, _count}}
    end

    test "a page with records that are not maps fails the request", %{state: state} do
      payload = %{"records" => [%{"id" => 1}, 5, "x", nil, %{"id" => 2}], "ref" => "1"}
      frame = Jason.encode!([nil, nil, "transfer:ABCD2345", "response:records", payload])

      assert {:ok, _state} = WebSocketClient.handle_frame({:text, frame}, state)
      assert_received {:sync_client, {:request_error, {:records, @table}, :invalid_response}}
      refute_received {:sync_client, {:records, _table, _result}}
    end
  end

  describe "the size of a remote site's answer" do
    setup do
      StubRemote.reset()
      on_exit(&StubRemote.reset/0)
      on_exit(fn -> Application.delete_env(:phoenix_kit_sync, :max_response_bytes) end)

      {:ok, connection, _token} =
        Connections.create_connection(%{
          "name" => "Stub sender #{System.unique_integer([:positive])}",
          "direction" => "receiver",
          "site_url" => StubRemote.url(),
          "status" => "active"
        })

      StubRemote.put_data(
        @table,
        for(id <- 1..50, do: %{"id" => id, "label" => String.duplicate("x", 200)})
      )

      {:ok, connection: connection}
    end

    test "an answer within the cap is pulled", %{connection: connection} do
      assert {:ok, %{imported: 50}} = ConnectionNotifier.pull_table_data(connection, @table)
    end

    test "an answer over the cap is dropped, and nothing of it is imported", %{
      connection: connection
    } do
      Application.put_env(:phoenix_kit_sync, :max_response_bytes, 2_000)

      assert {:error, :response_too_large} =
               ConnectionNotifier.pull_table_data(connection, @table)

      assert labels() == []
    end

    test "the cap holds for the table list too", %{connection: connection} do
      StubRemote.put_tables(for n <- 1..200, do: %{"name" => "table_#{n}", "row_count" => n})
      assert {:ok, tables} = ConnectionNotifier.fetch_sender_tables(connection)
      assert length(tables) == 200

      Application.put_env(:phoenix_kit_sync, :max_response_bytes, 500)
      assert {:error, :response_too_large} = ConnectionNotifier.fetch_sender_tables(connection)
    end
  end

  describe "status fetches from the Connections page" do
    defp receiver(status) do
      {:ok, connection, _token} =
        Connections.create_connection(%{
          "name" => "From: #{status}",
          "direction" => "receiver",
          # Nothing listens here: a request made to it comes back as an error.
          "site_url" => "http://localhost:9/#{status}-#{System.unique_integer([:positive])}",
          "status" => status
        })

      connection
    end

    test "only an active connection's site is contacted" do
      active = receiver("active")
      others = Enum.map(~w(pending suspended revoked expired), &receiver/1)

      Status.fetch_sender_statuses([active | others], self())

      active_uuid = active.uuid
      assert_receive {:sender_status_fetched, ^active_uuid, _status}, 5_000

      for other <- others do
        uuid = other.uuid
        refute_receive {:sender_status_fetched, ^uuid, _status}, 200
      end
    end
  end

  describe "status notifications" do
    test "a receiver connection's status change is not sent to the sender" do
      assert {:ok, :skipped} =
               ConnectionNotifier.notify_status_change(
                 %{direction: "receiver", site_url: "http://localhost:9", auth_token_hash: "h"},
                 "active"
               )
    end
  end
end
